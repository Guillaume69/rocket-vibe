// Derive aliases from the desktop's emoji-toolkit table (MIT JSON, no artwork).
// First code for a glyph matches rv-core::emoji and avoids duplicate reactions.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const source=new URL('../apps/desktop/crates/rv-core/data/emojis.tsv',import.meta.url);
const destination=new URL('../crates/rv-protocol/data/emoji-aliases.json',import.meta.url);
const glyphs=new Map(); const aliases=new Map();
for (const row of readFileSync(source,'utf8').trim().split(/\r?\n/)) {
  const [code,points]=row.split('\t');
  if (!code || !points) throw new Error('Invalid shared emoji row');
  if (!glyphs.has(points)) glyphs.set(points,code);
  aliases.set(code,glyphs.get(points));
}
const sorted=Object.fromEntries([...aliases].sort(([a],[b])=>a.localeCompare(b,'en')));
const outputs=[
  [destination,JSON.stringify(sorted,null,2)+'\n'],
  [new URL('../apps/mobile/fournisseurs/rocketvibe/emoji-aliases.generated.ts',import.meta.url),
    '// Generated by scripts/generate-native-emojis.mjs. Emoji-toolkit names, MIT.\nexport const EMOJI_ALIASES_JSON='+JSON.stringify(JSON.stringify(sorted))+';\n'],
];
if (!process.argv.includes('--check')) mkdirSync(new URL('../crates/rv-protocol/data/',import.meta.url),{recursive:true});
for (const [path,output] of outputs) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path,'utf8')!==output) throw new Error('Stale native emoji aliases');
  } else writeFileSync(path,output);
}
console.log(`Native emoji aliases: ${aliases.size} codes, ${glyphs.size} distinct glyphs.`);
