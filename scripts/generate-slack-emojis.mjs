#!/usr/bin/env node
// Generates Slack's standard emoji names for both apps from iamcal's
// emoji-datasource (MIT; its artwork is not used), the set Slack names its
// emoji from:
//   npm pack emoji-datasource@16.0.0 && tar xzf emoji-datasource-16.0.0.tgz
//   node scripts/generate-slack-emojis.mjs path/to/package
// Rows: name <TAB> code points (hex, dash-separated) <TAB> the five skin-tone
// variants Slack writes `:name::skin-tone-2:` to `:skin-tone-6:` for,
// comma-separated, or "-" when the emoji takes none. Deterministic: rerunning
// on the same version leaves git diff empty.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/generate-slack-emojis.mjs path/to/emoji-datasource');
  process.exit(1);
}
const emojis = JSON.parse(readFileSync(join(source, 'emoji.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8')).version;
const TONES = ['1F3FB', '1F3FC', '1F3FD', '1F3FE', '1F3FF'];

const rows = new Map();
for (const e of [...emojis].sort((a, b) => a.sort_order - b.sort_order)) {
  const tones = TONES.map((t) => e.skin_variations?.[t]?.unified);
  const toned = tones.every(Boolean) ? tones.join(',').toLowerCase() : '-';
  for (const name of e.short_names) {
    if (!rows.has(name)) rows.set(name, [e.unified.toLowerCase(), toned]);
  }
}
const lines = [...rows].map(([name, [points, toned]]) => `${name}\t${points}\t${toned}`);
writeFileSync(join(root, 'crates/rv-slack/data/slack-emojis.tsv'), lines.join('\n') + '\n');
writeFileSync(
  join(root, 'apps/mobile/lib/emojis.slack.generated.ts'),
  `// ⚠️ GENERATED by \`node scripts/generate-slack-emojis.mjs\` from emoji-datasource ${version}: do not edit by hand.
//
// Slack's standard emoji names, as rows of name <TAB> code points (hex) <TAB>
// the five skin-tone variants, comma-separated, or "-". See
// \`providers/slack/emojis.ts\`.
export const SLACK_EMOJIS = ${JSON.stringify(lines.join('\n'))};
`,
);
console.log(`${rows.size} names from emoji-datasource ${version}`);
