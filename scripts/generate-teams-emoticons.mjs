#!/usr/bin/env node
// Generates Teams' reaction ids for both apps from Microsoft's own reference
// table, "Teams Emoji Reactions Reference" (learn.microsoft.com), saved as HTML:
//   curl -o reactions.html https://learn.microsoft.com/en-us/microsoftteams/platform/agents-in-teams/teams-reactions-reference
//   node scripts/generate-teams-emoticons.mjs reactions.html
// Rows: id <TAB> code points (hex, dash-separated), for every id: named ones
// (`launch`) and those carrying their code points (`1f389_partypopper`), whose
// name part cannot be derived from Unicode's. Read both ways: a key shows as its
// glyph, and a glyph is sent as its key. A `-tone1` to `-tone5` suffix is a
// skin tone, left to the readers.
// Deterministic: rerunning on the same page leaves git diff empty.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/generate-teams-emoticons.mjs reactions.html');
  process.exit(1);
}
const page = readFileSync(source, 'utf8');
const text = (cell) =>
  cell
    .replace(/<[^>]+>/g, '')
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .trim();

const rows = new Map();
for (const [, row] of page.matchAll(/<tr>([\s\S]*?)<\/tr>/g)) {
  const cells = [...row.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)].map(([, c]) => text(c));
  if (cells.length < 3 || cells[0] === 'Emoji') continue;
  const [glyph, , id] = cells;
  if (!/^[a-z0-9_-]+$/.test(id) || rows.has(id)) continue;
  const points = [...glyph].map((c) => c.codePointAt(0).toString(16)).join('-');
  if (points) rows.set(id, points);
}
const lines = [...rows].sort(([a], [b]) => (a < b ? -1 : 1)).map(([id, points]) => `${id}\t${points}`);
writeFileSync(join(root, 'crates/rv-teams/data/teams-emoticons.tsv'), lines.join('\n') + '\n');
writeFileSync(
  join(root, 'packages/provider-teams/src/emoticons.generated.ts'),
  `// ⚠️ GENERATED by \`node scripts/generate-teams-emoticons.mjs\` from Microsoft's
// "Teams Emoji Reactions Reference": do not edit by hand.
//
// Teams' reaction ids, as rows of id <TAB> code points (hex, dash-separated).
export const TEAMS_EMOTICONS = ${JSON.stringify(lines.join('\n'))};
`,
);
console.log(`${rows.size} ids`);
